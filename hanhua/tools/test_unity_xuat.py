    def test_diagnose_hooks_from_log_text(self) -> None:
        import tempfile

        flood = (
            "[Info   :   BepInEx] Loading [XUnity Auto Translator 5.6.2]\n"
            "[Warning:XUnity.AutoTranslator] Cannot hook 'TMPro.TMP_Text.set_text'. "
            "Harmony is not supported in this runtime and no alternate MonoMod hook "
            "has been implemented. Failing hook: 'TMP_Text_text_Hook'.\n"
        ) * 6
        healthy = (
            "[Info   :   BepInEx] Loading [XUnity Auto Translator 5.6.2]\n"
            "[Info   :   BepInEx] Loading [AutoTranslator.IL2CPP.BruteForceFix 1.0.3]\n"
            "[Warning:XUnity.AutoTranslator] Could not hook 'TMP_Text_SetCharArray_Hook3'. "
            "Likely due differences between different versions of the engine or text framework.\n"
            "[Info   :XUnity.AutoTranslator] Loaded XUnity.AutoTranslator into Unity [6000.3.5f2] game.\n"
        )
        missing_bf = (
            "[Info   :   BepInEx] Loading [XUnity Auto Translator 5.6.2]\n"
            "[Info   :XUnity.AutoTranslator] Loaded XUnity.AutoTranslator into Unity [6000.3.5f2] game.\n"
        )
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "GameAssembly.dll").write_bytes(b"x")
            none = unity_xuat.diagnose_hooks(root)
            self.assertTrue(none.ok)
            self.assertEqual(none.code, "no_log")

            flood_report = unity_xuat.diagnose_hooks(root, text=flood)
            self.assertFalse(flood_report.ok)
            self.assertEqual(flood_report.code, "harmony_flood")
            self.assertIn("ForceMonoModHooks", flood_report.message)

            healthy_report = unity_xuat.diagnose_hooks(root, text=healthy)
            self.assertTrue(healthy_report.ok)
            self.assertEqual(healthy_report.code, "ok")

            plugin = root / "BepInEx" / "plugins"
            plugin.mkdir(parents=True)
            (plugin / "AutoTranslator.IL2CPP.BruteForceFix.dll").write_bytes(b"x")
            bf = unity_xuat.diagnose_hooks(root, text=missing_bf)
            self.assertFalse(bf.ok)
            self.assertEqual(bf.code, "bruteforce_missing")

