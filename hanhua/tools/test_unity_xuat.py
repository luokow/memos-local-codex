    def test_fill_dump_batches_galtransl_official_chunk(self) -> None:
        # Sakura-GalTransl-7B-v3.7 card: 7-10 sentences per request.
        # GalTransl's generic gpt.numPerRequestTranslate cap is 16.
        import os
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            folder = unity_xuat.text_dir(root)
            folder.mkdir(parents=True)
            lines = [f"確認テスト文{i:02d}=確認テスト文{i:02d}\n" for i in range(20)]
            (folder / unity_xuat.PREEXTRACT_NAME).write_text(
                "".join(lines), encoding="utf-8"
            )
            sizes: list[int] = []

            def fake(batch: list[str]) -> list[str]:
                sizes.append(len(batch))
                return [f"这是测试句{i:02d}" for i, _ in enumerate(batch)]

            old_chunk = os.environ.pop("HANHUA_FILL_CHUNK", None)
            try:
                filled, total = unity_xuat.fill_dump(root, fake)
            finally:
                if old_chunk is not None:
                    os.environ["HANHUA_FILL_CHUNK"] = old_chunk
            self.assertEqual(total, 20)
            self.assertEqual(filled, 20)
            self.assertEqual(sizes, [8, 8, 4])

