import unity_xuat

TOOLS = Path(__file__).resolve().parent
PACK = TOOLS.parent
SRC = (TOOLS / "unity_xuat.py").read_text(encoding="utf-8")
CLICK = (TOOLS / "one_click_unity.py").read_text(encoding="utf-8")


class UnityXuatTests(unittest.TestCase):
    def test_shared_tools_have_no_circlemate_lines(self) -> None:
        blob = SRC + "\n" + CLICK
        for needle in (
            "澄華",
            "兎美",
            "チルニャン",
            "RJ01544625",
            "CIRCLEMATE",
            "datelabel_prolouge",
            "保险金",
        ):
            self.assertNotIn(needle, blob)

    def test_escaped_equals_roundtrip(self) -> None:
        src = "icon <sprite=0> text"
        line = f"{unity_xuat.xuat_escape(src)}=图标"
        parts = unity_xuat.xuat_split(line)
        self.assertIsNotNone(parts)
        self.assertEqual(unity_xuat.xuat_unescape(parts[0]), src)
        self.assertEqual(unity_xuat.xuat_unescape(parts[1]), "图标")

    def test_identity_and_pending(self) -> None:
        mapping = {
            "こんにちは": "こんにちは",
            "設定": "设置",
            "hello": "hello",
            "r:^x$": "y",
            "長い日文": "还是日文です",
        }
        self.assertTrue(unity_xuat.is_identity("こんにちは", "こんにちは"))
        pending = unity_xuat.pending_for_fill(mapping)
        self.assertIn("こんにちは", pending)
        self.assertIn("長い日文", pending)
        self.assertNotIn("設定", pending)
        self.assertNotIn("hello", pending)
        self.assertNotIn(
            "射精",
            unity_xuat.pending_for_fill({"射精": "射精"}),
        )
        chart = "あいうえおかきくけこしすせそたちつてとなにぬねの"
        self.assertNotIn(chart, unity_xuat.pending_for_fill({chart: chart}))

    def test_missing_loc_regex_is_not_autogen_file(self) -> None:
        self.assertFalse(unity_xuat.MISSING_LOC_NOTE.startswith("_"))
        self.assertNotIn("r:", unity_xuat.MISSING_LOC_NOTE)

